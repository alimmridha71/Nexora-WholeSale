-- =====================================================================
-- Nexora Wholesale - database schema (PostgreSQL 15+ / Supabase)
-- ---------------------------------------------------------------------
-- Creates the complete schema on an EMPTY database, in one transaction.
-- Equivalent to the Laravel migrations in database/migrations (plus extra
-- CHECK constraints for non-negative amounts) and marks
-- them as applied, so `php artisan migrate` will not re-run them.
--
-- Apply with ONE of:
--   * Supabase dashboard > SQL Editor > paste this file > Run
--   * psql "postgresql://postgres.<ref>:<password>@<pooler-host>:5432/postgres?sslmode=require" -f database/schema.sql
--   * or skip this file and run `php artisan migrate` (same result)
-- Then, optionally, database/seed.sql for demo data.
--
-- MySQL users: run `php artisan migrate` instead (migrations are portable).
-- =====================================================================

BEGIN;

-- ---------------------------------------------------------------------
-- Laravel migration bookkeeping
-- ---------------------------------------------------------------------
CREATE TABLE migrations (
    id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    migration varchar(255) NOT NULL,
    batch     integer NOT NULL
);

-- ---------------------------------------------------------------------
-- users
-- ---------------------------------------------------------------------
CREATE TABLE users (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              varchar(255) NOT NULL,
    email             varchar(255) NOT NULL,
    email_verified_at timestamp(0) NULL,
    password          varchar(255) NOT NULL,
    role              varchar(255) NOT NULL DEFAULT 'retailer'
                      CHECK (role IN ('admin', 'retailer', 'wholesaler', 'distributor')),
    remember_token    varchar(100) NULL,
    created_at        timestamp(0) NULL,
    updated_at        timestamp(0) NULL,
    CONSTRAINT users_email_unique UNIQUE (email)
);
CREATE INDEX users_role_index ON users (role);

CREATE TABLE password_reset_tokens (
    email      varchar(255) PRIMARY KEY,
    token      varchar(255) NOT NULL,
    created_at timestamp(0) NULL
);

CREATE TABLE sessions (
    id            varchar(255) PRIMARY KEY,
    user_id       bigint NULL REFERENCES users (id) ON DELETE CASCADE,
    ip_address    varchar(45) NULL,
    user_agent    text NULL,
    payload       text NOT NULL,
    last_activity integer NOT NULL
);
CREATE INDEX sessions_user_id_index ON sessions (user_id);
CREATE INDEX sessions_last_activity_index ON sessions (last_activity);

-- ---------------------------------------------------------------------
-- products
-- ---------------------------------------------------------------------
CREATE TABLE products (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        varchar(255) NOT NULL,
    slug        varchar(255) NOT NULL,
    description text NULL,
    image       varchar(255) NULL,
    base_price  numeric(12, 2) NOT NULL CHECK (base_price >= 0),
    stock       integer NOT NULL DEFAULT 0 CHECK (stock >= 0),
    sku         varchar(64) NOT NULL,
    created_at  timestamp(0) NULL,
    updated_at  timestamp(0) NULL,
    CONSTRAINT products_slug_unique UNIQUE (slug),
    CONSTRAINT products_sku_unique UNIQUE (sku)
);
CREATE INDEX products_name_base_price_index ON products (name, base_price);

-- ---------------------------------------------------------------------
-- bulk_prices (tiered pricing; max_quantity NULL = open-ended top tier)
-- FK index: product_id is the leading column of the composite index.
-- ---------------------------------------------------------------------
CREATE TABLE bulk_prices (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id     bigint NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    min_quantity   integer NOT NULL CHECK (min_quantity >= 1),
    max_quantity   integer NULL CHECK (max_quantity IS NULL OR max_quantity >= min_quantity),
    price_per_unit numeric(12, 2) NOT NULL CHECK (price_per_unit >= 0),
    created_at     timestamp(0) NULL,
    updated_at     timestamp(0) NULL
);
CREATE INDEX bulk_prices_product_id_min_quantity_max_quantity_index
    ON bulk_prices (product_id, min_quantity, max_quantity);

-- ---------------------------------------------------------------------
-- quotes (custom B2B inquiries)
-- FK index: user_id is the leading column of the composite index.
-- ---------------------------------------------------------------------
CREATE TABLE quotes (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference            varchar(20) NOT NULL,
    user_id              bigint NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    product_details_json json NOT NULL,
    target_price         numeric(12, 2) NULL CHECK (target_price IS NULL OR target_price >= 0),
    status               varchar(255) NOT NULL DEFAULT 'pending'
                         CHECK (status IN ('pending', 'under_review', 'approved', 'rejected', 'expired')),
    message              text NULL,
    created_at           timestamp(0) NULL,
    updated_at           timestamp(0) NULL,
    CONSTRAINT quotes_reference_unique UNIQUE (reference)
);
CREATE INDEX quotes_user_id_status_index ON quotes (user_id, status);
CREATE INDEX quotes_status_created_at_index ON quotes (status, created_at);

-- ---------------------------------------------------------------------
-- Supabase Data API lock-down (same as migration 2026_11_05_000001).
-- Laravel connects as the table owner; the anon/authenticated roles used
-- by the publishable key get NO access: RLS on, no policies, privileges revoked.
-- ---------------------------------------------------------------------
ALTER TABLE migrations            ENABLE ROW LEVEL SECURITY;
ALTER TABLE users                 ENABLE ROW LEVEL SECURITY;
ALTER TABLE password_reset_tokens ENABLE ROW LEVEL SECURITY;
ALTER TABLE sessions              ENABLE ROW LEVEL SECURITY;
ALTER TABLE products              ENABLE ROW LEVEL SECURITY;
ALTER TABLE bulk_prices           ENABLE ROW LEVEL SECURITY;
ALTER TABLE quotes                ENABLE ROW LEVEL SECURITY;

DO $$
DECLARE r text;
BEGIN
    FOREACH r IN ARRAY ARRAY['anon', 'authenticated'] LOOP
        IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = r) THEN
            EXECUTE format('REVOKE ALL ON ALL TABLES IN SCHEMA public FROM %I', r);
            EXECUTE format('REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM %I', r);
            EXECUTE format('ALTER DEFAULT PRIVILEGES IN SCHEMA public REVOKE ALL ON TABLES FROM %I', r);
            EXECUTE format('ALTER DEFAULT PRIVILEGES IN SCHEMA public REVOKE ALL ON SEQUENCES FROM %I', r);
        END IF;
    END LOOP;
END
$$;

-- Mark the Laravel migrations as applied.
INSERT INTO migrations (migration, batch) VALUES
    ('0001_01_01_000000_create_users_table', 1),
    ('2026_11_04_000001_create_products_table', 1),
    ('2026_11_04_000002_create_bulk_prices_table', 1),
    ('2026_11_04_000003_create_quotes_table', 1),
    ('2026_11_05_000001_lock_down_supabase_data_api', 1);

COMMIT;
